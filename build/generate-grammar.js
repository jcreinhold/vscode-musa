#!/usr/bin/env node
/**
 * Generate `syntaxes/musa.tmLanguage.json` from the musa repository's
 * committed highlighting fixtures.
 *
 * VS Code wants a TextMate grammar for instant highlighting; the language
 * server refines it with semantic tokens a beat later. What this build step
 * refuses to do is own a vocabulary: the keywords, units, and punctuation
 * come from `spellings.json`, the class list from `token-classes.json` —
 * the same committed fixtures the desktop's highlighter is generated from —
 * and the patterns trace to `crates/musa-language/src/lexer.rs`, whose
 * regexes are cited at each step.
 *
 *   node build/generate-grammar.js          # write the grammar
 *   node build/generate-grammar.js --check  # fail if the committed one is stale
 *
 * The musa repository is found at $MUSA_REPO, else `../musa`.
 */

'use strict';

const { readFileSync, writeFileSync, existsSync } = require('node:fs');
const { join } = require('node:path');

const MUSA_REPO = process.env.MUSA_REPO || join(__dirname, '..', '..', 'musa');
const FIXTURES = join(MUSA_REPO, 'apps/musa-desktop/ui/src/lib/session/generated');
const OUTPUT = join(__dirname, '..', 'syntaxes', 'musa.tmLanguage.json');

/** The TextMate scope each `TokenClass` paints with. */
const SCOPES = {
  comment: 'comment',
  keyword: 'keyword.control.musa',
  use: 'keyword.control.import.musa',
  pitch: 'constant.other.pitch.musa',
  duration: 'constant.numeric.duration.musa',
  number: 'constant.numeric.musa',
  text: 'string.quoted.double.musa',
  unit: 'constant.other.unit.musa',
  name: 'variable.other.musa',
  punctuation: 'keyword.operator.musa',
  invalid: 'invalid.illegal.musa',
};

/** Escape a literal spelling for a regex. */
const escaped = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Escape a literal for placement inside a JSON string. */
const words = (list) => list.map(escaped).join('|');

/** Read the fixtures, or say plainly what is missing. */
function loadFixtures() {
  for (const name of ['spellings.json', 'token-classes.json']) {
    if (!existsSync(join(FIXTURES, name))) {
      console.error(
        `${name} not found at ${FIXTURES}\n` +
          'Set MUSA_REPO to a checkout of the musa repository (the fixtures are generated there).',
      );
      process.exit(1);
    }
  }
  const spellings = JSON.parse(readFileSync(join(FIXTURES, 'spellings.json'), 'utf8'));
  const classes = JSON.parse(readFileSync(join(FIXTURES, 'token-classes.json'), 'utf8'));
  return { spellings, classes };
}

/** Build the grammar object from the fixtures. Exported for the tests. */
function build(spellings, classes) {
  // A class the generator has never heard of is the drift law speaking:
  // the lexer grew a class and this table was not taught it.
  for (const name of classes) {
    if (!(name in SCOPES)) {
      throw new Error(`TokenClass "${name}" has no TextMate scope in build/generate-grammar.js`);
    }
  }

  const byClass = new Map();
  for (const [text, className] of spellings) {
    if (!byClass.has(className)) byClass.set(className, []);
    byClass.get(className).push(text);
  }
  const keywords = (byClass.get('keyword') ?? []).slice().sort();
  const units = (byClass.get('unit') ?? []).slice().sort();
  const marks = (byClass.get('punctuation') ?? []).slice().sort();
  const operators = marks.filter((mark) => ['->', '|>', '=', '-', '~'].includes(mark));
  const brackets = marks.filter((mark) => ['{', '}', '[', ']', '(', ')'].includes(mark));
  const separators = marks.filter((mark) => !operators.includes(mark) && !brackets.includes(mark));

  return {
    $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
    comment:
      'GENERATED by build/generate-grammar.js from the musa repository’s highlighting fixtures — do not edit. Patterns trace to crates/musa-language/src/lexer.rs.',
    name: 'musa',
    scopeName: 'source.musa',
    patterns: [
      { include: '#comments' },
      { include: '#string' },
      { include: '#keywords' },
      { include: '#use' },
      { include: '#units' },
      { include: '#pitch' },
      { include: '#interval' },
      { include: '#numbers' },
      { include: '#operators' },
      { include: '#brackets' },
      { include: '#separators' },
      { include: '#name' },
    ],
    repository: {
      // `//[^\n]*` and `(?s)/\*([^*]|\*[^/])*\*/` (the lexer’s own pair).
      comments: {
        patterns: [
          {
            name: 'comment.line.double-slash.musa',
            match: '//[^\\n]*',
          },
          {
            name: 'comment.block.musa',
            begin: '/\\*',
            end: '\\*/',
          },
        ],
      },
      // `"([^"\\\n]|\\[^\n])*"` — one quoted line; a newline ends it.
      string: {
        name: SCOPES.text,
        begin: '"',
        end: '"',
        patterns: [{ name: 'constant.character.escape.musa', match: '\\\\[^\\n]' }],
      },
      // The spelled keywords, priority 3 in the lexer — they beat the name
      // pattern here exactly as they do there.
      keywords: {
        patterns: [{ name: SCOPES.keyword, match: `\\b(${words(keywords)})\\b` }],
      },
      use: {
        patterns: [{ name: SCOPES.use, match: '\\buse\\b' }],
      },
      units: {
        patterns: [{ name: SCOPES.unit, match: `\\b(${words(units)})\\b` }],
      },
      // `[a-g](ss|ff|[sfn])?-?[0-9]+` — a written pitch.
      pitch: {
        patterns: [{ name: SCOPES.pitch, match: '\\b[a-g](ss|ff|[sfn])?-?[0-9]+\\b' }],
      },
      // `[PMm][0-9]+` — an interval: quality and size.
      interval: {
        patterns: [{ name: SCOPES.pitch, match: '\\b[PMm][0-9]+\\b' }],
      },
      // Rational, float, integer — the lexer’s own order.
      numbers: {
        patterns: [
          { name: SCOPES.duration, match: '\\b[0-9]+/[0-9]+\\b' },
          { name: SCOPES.number, match: '\\b[0-9]+\\.[0-9]+\\b' },
          { name: SCOPES.number, match: '\\b[0-9]+\\b' },
        ],
      },
      operators: {
        patterns: [{ name: SCOPES.punctuation, match: words(operators) }],
      },
      brackets: {
        patterns: [{ name: 'punctuation.section.musa', match: words(brackets) }],
      },
      separators: {
        patterns: [{ name: 'punctuation.separator.musa', match: words(separators) }],
      },
      // `[a-zA-Z_]+` — everything the composer named, after every spelled
      // word has had its turn, exactly as the identifier follows the
      // keywords in the lexer.
      name: {
        patterns: [{ name: SCOPES.name, match: '[a-zA-Z_]+' }],
      },
    },
  };
}

function main() {
  const check = process.argv.includes('--check');
  const { spellings, classes } = loadFixtures();
  const grammar = `${JSON.stringify(build(spellings, classes), null, 2)}\n`;
  const committed = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : undefined;
  if (check) {
    if (committed !== grammar) {
      console.error(`${OUTPUT} is stale — rerun \`npm run grammar\` and commit the result`);
      process.exit(1);
    }
    console.log('textmate grammar is fresh');
    return;
  }
  writeFileSync(OUTPUT, grammar);
  console.log(`wrote ${OUTPUT}`);
}

if (require.main === module) {
  main();
}

module.exports = { build, SCOPES };
